"""
音质优化：编码器协商、重采样质量、采样率。

蓝牙 A2DP 接收端的音质由三层决定，本模块管前两层（第三层是 EQ，在 eq.py）：

**第 1 层：编码器**（影响最大）
- SBC：强制基线，码率约 328 kbps，音质一般
- **SBC-XQ**：SBC 的高质量变体，码率 ~452 kbps，**音质明显好于 SBC**，
  且几乎所有设备都兼容（因为仍是 SBC 家族）—— 这是最划算的提升
- AAC：手机端支持好，码率 ~256 kbps，但 Linux 端解码质量有争议
- LDAC / aptX HD：高码率，但需要对方支持，且链路差时反而卡顿

**第 2 层：重采样质量**（容易被忽略）
PipeWire 的 `resample.quality` 默认值在不同版本差异很大：
- 1.4 及更早：默认 4（较低，44.1k↔48k 转换会有可闻劣化）
- 1.6+：默认提到 7
蓝牙 A2DP 通常协商到 48kHz，而手机音源多是 44.1kHz，
**几乎必然发生 44.1→48 的重采样**，所以这个参数直接影响听感。

本模块把 `resample.quality` 提到 10（音质与 CPU 的平衡点；
10 与 15 听感差异极小但 CPU 翻倍，见 ArchWiki）。

**第 3 层：EQ**（见 eq.py，可选）
"""

import os
import re

from bt import BtError, run_cmd, which

QUALITY_CONF_NAME = "55-bt-speaker-quality.conf"
# 重采样配置写到这里（PipeWire 目录，不是 WirePlumber）
PIPEWIRE_RESAMPLE_NAME = "55-bt-speaker-resample.conf"

# 编码器预设。
# `codecs` 是要在 bluez5.codecs 里启用的列表（按优先级从高到低）。
#
# ⚠️ 这里**不存显示文案**，只存 i18n key。
#
# 为什么？—— 真机反馈「切英文界面后音质预设还是中文」。根因是后端
# 直接返回了中文字符串，前端只是原样显示。文案属于展示层，必须由前端
# 按当前语言翻译。这和 v2.5.0 修「自检项返回中文」是同一类问题，
# 当时只修了自检项，漏了预设列表。
CODEC_PRESETS = {
    "balanced": {
        "label_key": "codec.balanced",
        "desc_key": "codec.balancedDesc",
        "codecs": ["sbc_xq", "aac", "sbc"],
        "resample": 10,
    },
    "quality": {
        "label_key": "codec.quality",
        "desc_key": "codec.qualityDesc",
        "codecs": ["ldac", "aptx_hd", "aac", "sbc_xq", "sbc"],
        "resample": 15,
    },
    "stable": {
        "label_key": "codec.stable",
        "desc_key": "codec.stableDesc",
        "codecs": ["sbc"],
        "resample": 10,
    },
}

DEFAULT_CODEC = "balanced"


def codec_list():
    return [
        {"key": k, "label_key": v["label_key"], "desc_key": v["desc_key"],
         "resample": v["resample"]}
        for k, v in CODEC_PRESETS.items()
    ]


def build_quality_conf(preset_key):
    """生成编码器 + 重采样质量的配置。

    ⚠️⚠️ 两个历史 bug（v3.3.1 修）
    ----------------------------
    **1. `hw-volume` 把已经修好的问题又带回来了**

    这份配置写成 `bluez5.hw-volume = [ a2dp_sink a2dp_source ]`，
    而 `bt.py` 的 `50-bt-speaker.conf` 特意只留 `a2dp_source`，并用大段
    注释解释了原因：带上 `a2dp_sink` 会把音量控制权通过 AVRCP 绝对音量
    交给对端，Windows 的滑块会直接改 Deck 音量（真机反馈过
    「电脑声音小、手机没问题」）。

    两份配置都加载，而 `55-bt-speaker-quality.conf` 按文件名排序在后、
    **覆盖**前面那份 —— 于是用户一切换音质预设，那个已经修好的 bug
    就回来了。现在统一只留 `a2dp_source`。

    **2. `context.properties` 放错了目录**

    `default.clock.rate` / `resample.quality` 是 **PipeWire 主配置**的键，
    WirePlumber 不认。原来写在 `wireplumber.conf.d/` 下，等于这两行
    从未生效（「重采样质量提到 10」是个安慰剂）。现在拆成两个文件：
    蓝牙部分留在 WirePlumber，重采样部分写到 `pipewire.conf.d/`。
    """
    resolved = preset_key if preset_key in CODEC_PRESETS else DEFAULT_CODEC
    p = CODEC_PRESETS[resolved]
    codecs = " ".join(p["codecs"])
    return """# Generated by the "Bluetooth Speaker" Decky plugin — audio quality
# 由「蓝牙音箱」Decky 插件生成 —— 音质优化
# Path / 位置: ~/.config/wireplumber/wireplumber.conf.d/{name}
# Preset / 预设: {resolved}
# Delete this file and restart WirePlumber to restore defaults.
# 删除本文件并重启 WirePlumber 即可恢复默认。

monitor.bluez.properties = {{
  # Codec priority: earlier entries are negotiated first.
  # 编码器优先级：列表里靠前的优先协商
  bluez5.codecs = [ {codecs} ]
  # SBC-XQ: high-quality SBC variant, ~452 kbps, almost no compatibility loss.
  # SBC-XQ：SBC 的高质量变体，码率约 452 kbps，兼容性几乎无损失
  bluez5.enable-sbc-xq = true
  # Hardware volume: a2dp_source only. Do NOT add a2dp_sink here.
  # 硬件音量：只保留 a2dp_source，**不要**加 a2dp_sink。
  #
  # With a2dp_sink in hw-volume, volume control is handed to the PEER via
  # AVRCP absolute volume. Windows implements it fully, so the PC's slider
  # directly sets the Deck's volume (reported on hardware as
  # "PC audio is quiet, phone is fine"). See 50-bt-speaker.conf.
  # 加上 a2dp_sink 会把音量控制权交给对端（Windows 滑块直接改 Deck 音量），
  # 详见 50-bt-speaker.conf 里的说明。
  bluez5.hw-volume = [ a2dp_source ]
}}
""".format(
        name=QUALITY_CONF_NAME,
        resolved=resolved,
        codecs=codecs,
    )


# 重采样质量配置 —— **必须**写到 PipeWire 目录，WirePlumber 不认这些键。
#
# 为什么单独一个文件？
# ------------------
# `default.clock.rate` / `resample.quality` 属于 PipeWire 主配置
# （`context.properties`）。放在 `wireplumber.conf.d/` 下会被 WirePlumber
# 当成不认识的段直接忽略 —— 早期版本就是这么写的，所以「重采样质量
# 提到 10」这一项**从未生效**。
def build_resample_conf(preset_key):
    """生成重采样质量配置（写到 PipeWire 目录）。"""
    resolved = preset_key if preset_key in CODEC_PRESETS else DEFAULT_CODEC
    p = CODEC_PRESETS[resolved]
    return """# Generated by the "Bluetooth Speaker" Decky plugin — resample quality
# 由「蓝牙音箱」Decky 插件生成 —— 重采样质量
# Path / 位置: ~/.config/pipewire/pipewire.conf.d/{name}
# Preset / 预设: {resolved}

context.properties = {{
  # Bluetooth usually negotiates 48 kHz while phones mostly output 44.1 kHz,
  # so resampling is almost always involved.
  # 蓝牙通常协商 48kHz，而手机音源多为 44.1kHz，几乎必然重采样。
  #
  # PipeWire 1.4 defaults to 4 (low; audible degradation on 44.1<->48),
  # 1.6 raised it to 7. {resample} is the quality/CPU sweet spot
  # (10 vs 15 is barely audible but doubles CPU).
  # 1.4 默认 4（偏低），1.6 提到 7。{resample} 是音质与 CPU 的平衡点。
  default.clock.rate = 48000
  resample.quality = {resample}
}}
""".format(
        name=PIPEWIRE_RESAMPLE_NAME,
        resolved=resolved,
        resample=p["resample"],
    )


class QualityConfig:
    """管理音质优化配置。"""

    def __init__(self, log=None):
        self._log = log or (lambda *_: None)

    @staticmethod
    def _cfg_base():
        return os.environ.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")

    @classmethod
    def conf_path(cls):
        return os.path.join(cls._cfg_base(), "wireplumber", "wireplumber.conf.d", QUALITY_CONF_NAME)

    @classmethod
    def resample_path(cls):
        """重采样配置的路径（PipeWire 目录）。

        ⚠️ 必须是 `pipewire/pipewire.conf.d/`，不是 `wireplumber/...`：
        `default.clock.rate` / `resample.quality` 是 PipeWire 主配置的键，
        WirePlumber 读到会当成未知段忽略（早期版本就写错了目录，
        所以这项设置从未生效）。
        """
        return os.path.join(cls._cfg_base(), "pipewire", "pipewire.conf.d",
                            PIPEWIRE_RESAMPLE_NAME)

    @classmethod
    def installed(cls):
        try:
            return os.path.isfile(cls.conf_path())
        except Exception:
            return False

    @staticmethod
    def _write_atomic(path, text):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        tmp = path + ".tmp"
        with open(tmp, "w", encoding="utf-8") as f:
            f.write(text)
        os.replace(tmp, path)

    def apply(self, preset_key):
        path = self.conf_path()
        try:
            self._write_atomic(path, build_quality_conf(preset_key))
            # 重采样质量写到 PipeWire 目录（独立文件，独立目录）
            self._write_atomic(self.resample_path(),
                               build_resample_conf(preset_key))
        except Exception as e:  # noqa: BLE001
            raise BtError("写入音质配置失败：%s" % e)
        self._log("已写入音质配置（%s）：%s" % (preset_key, path))
        return path

    def remove(self):
        path = self.conf_path()
        try:
            if os.path.exists(path):
                os.remove(path)
                self._log("已删除音质配置：%s" % path)
            # 重采样文件也要一起删，否则「恢复默认」只恢复了一半
            rp = self.resample_path()
            if os.path.exists(rp):
                os.remove(rp)
                self._log("已删除重采样配置：%s" % rp)
        except Exception as e:  # noqa: BLE001
            raise BtError("删除音质配置失败：%s" % e)
        return True

    def current(self):
        path = self.conf_path()
        if not os.path.exists(path):
            return None
        try:
            with open(path, "r", encoding="utf-8") as f:
                text = f.read()
        except Exception:
            return None
        # 兼容两种注释格式：
        #   新版（中英双语）: "Preset / 预设: balanced"
        #   旧版（纯中文）   : "预设：balanced"
        m = re.search(r"(?:Preset / 预设|预设)[:：]\s*(\w+)", text)
        return m.group(1) if m and m.group(1) in CODEC_PRESETS else None


